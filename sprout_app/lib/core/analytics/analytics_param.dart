/// Analytics event parameter name constants.
abstract final class AnalyticsParam {
  /// Screen name parameter for screen_view events.
  ///
  /// Allowed values: [AnalyticsScreenName]
  static const String screenName = 'screen_name';

  /// Sign-in/sign-up method parameter.
  ///
  /// Allowed values: [AnalyticsSignInMethod]
  static const String method = 'method';
}
